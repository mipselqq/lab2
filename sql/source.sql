CREATE TABLE public.accounts (
    account_id bigint GENERATED BY DEFAULT AS IDENTITY (START WITH 1000) PRIMARY KEY,
    owner_name text NOT NULL,
    status text NOT NULL CHECK (status IN ('OPEN', 'FROZEN', 'CLOSED'))
);

